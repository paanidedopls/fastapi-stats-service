import time
import uuid
from fastapi import FastAPI, HTTPException, Query
from starlette.middleware.cors import CORSMiddleware
from starlette.types import ASGIApp, Message, Receive, Scope, Send

EMAIL = "24f2001785@ds.study.iitm.ac.in"
ALLOWED_ORIGIN = "https://dash-de9fkt.example.com"

api = FastAPI(title="Descriptive Statistics API", version="1.0.0")


@api.get("/stats")
async def stats(values: str = Query(..., description="Comma-separated integers")):
    """Compute descriptive statistics from a comma-separated integer list."""
    raw_items = values.split(",")
    try:
        numbers = [int(item.strip()) for item in raw_items]
    except ValueError as exc:
        raise HTTPException(
            status_code=400,
            detail="values must be a comma-separated list of integers",
        ) from exc

    if not numbers:
        raise HTTPException(status_code=400, detail="values must not be empty")

    total = sum(numbers)
    return {
        "email": EMAIL,
        "count": len(numbers),
        "sum": total,
        "min": min(numbers),
        "max": max(numbers),
        "mean": total / len(numbers),
    }


@api.get("/")
async def health():
    return {"status": "ok", "service": "descriptive-statistics"}


class RequestMetadataMiddleware:
    """Add an ID and elapsed-time header to every HTTP response, including CORS preflights."""

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        started = time.perf_counter()
        request_id = str(uuid.uuid4())

        async def send_with_metadata(message: Message) -> None:
            if message["type"] == "http.response.start":
                elapsed = max(0.0, time.perf_counter() - started)
                headers = list(message.get("headers", []))
                headers.append((b"x-request-id", request_id.encode("ascii")))
                headers.append((b"x-process-time", f"{elapsed:.6f}".encode("ascii")))
                message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_with_metadata)


# Wrap CORS with metadata middleware so headers are also present on OPTIONS responses
# generated by CORSMiddleware and on its rejected preflight responses.
_cors_app = CORSMiddleware(
    app=api,
    allow_origins=[ALLOWED_ORIGIN],
    allow_credentials=False,
    allow_methods=["GET"],
    allow_headers=["*"],
    max_age=600,
)
app = RequestMetadataMiddleware(_cors_app)
